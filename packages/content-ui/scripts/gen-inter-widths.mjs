// Generates src/fonts/inter-widths.ts from the pinned @fontsource/inter WOFF files.
// Deterministic: same font package version -> same table. Run via `pnpm gen:widths` after bumping the font.
import { inflateSync } from "node:zlib";
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const here = path.dirname(fileURLToPath(import.meta.url));
// Usage: node gen-inter-widths.mjs [family=inter] [weights=400,500,600,700]
// Every pinned family gets its own table: `inter` -> inter-widths.ts, `sora` -> sora-widths.ts.
const FAMILY = (process.argv[2] ?? "inter").toLowerCase();
const WEIGHTS = (process.argv[3] ?? (FAMILY === "sora" ? "600,700,800" : "400,500,600,700")).split(",").map(Number);
const CONST = FAMILY.toUpperCase();
const fontDir = path.dirname(require.resolve(`@fontsource/${FAMILY}/package.json`));
const fontPkg = JSON.parse(readFileSync(path.join(fontDir, "package.json"), "utf8"));

function parseWoff(buf) {
  if (buf.toString("ascii", 0, 4) !== "wOFF") throw new Error("not a WOFF file");
  const numTables = buf.readUInt16BE(12);
  const tables = new Map();
  for (let i = 0; i < numTables; i++) {
    const o = 44 + i * 20;
    const tag = buf.toString("ascii", o, o + 4);
    const offset = buf.readUInt32BE(o + 4);
    const compLength = buf.readUInt32BE(o + 8);
    const origLength = buf.readUInt32BE(o + 12);
    const raw = buf.subarray(offset, offset + compLength);
    tables.set(tag, compLength < origLength ? inflateSync(raw) : Buffer.from(raw));
  }
  return tables;
}

function cmapToGlyph(cmap) {
  const n = cmap.readUInt16BE(2);
  const map = new Map();
  for (let i = 0; i < n; i++) {
    const off = cmap.readUInt32BE(4 + i * 8 + 4);
    const format = cmap.readUInt16BE(off);
    if (format === 4) {
      const segX2 = cmap.readUInt16BE(off + 6);
      const seg = segX2 / 2;
      const ends = off + 14, starts = ends + segX2 + 2, deltas = starts + segX2, ranges = deltas + segX2;
      for (let s = 0; s < seg; s++) {
        const end = cmap.readUInt16BE(ends + s * 2);
        const start = cmap.readUInt16BE(starts + s * 2);
        const delta = cmap.readInt16BE(deltas + s * 2);
        const rangeOff = cmap.readUInt16BE(ranges + s * 2);
        if (start === 0xffff) continue;
        for (let c = start; c <= end; c++) {
          let g;
          if (rangeOff === 0) g = (c + delta) & 0xffff;
          else {
            const gi = ranges + s * 2 + rangeOff + (c - start) * 2;
            if (gi + 1 >= cmap.length) continue;
            g = cmap.readUInt16BE(gi);
            if (g !== 0) g = (g + delta) & 0xffff;
          }
          if (g !== 0 && !map.has(c)) map.set(c, g);
        }
      }
    } else if (format === 12) {
      const nGroups = cmap.readUInt32BE(off + 12);
      for (let g = 0; g < nGroups; g++) {
        const p = off + 16 + g * 12;
        const start = cmap.readUInt32BE(p), end = cmap.readUInt32BE(p + 4), gid = cmap.readUInt32BE(p + 8);
        for (let c = start; c <= end; c++) if (!map.has(c)) map.set(c, gid + (c - start));
      }
    }
  }
  return map;
}

function widthsFor(weight) {
  const file = path.join(fontDir, "files", `${FAMILY}-latin-${weight}-normal.woff`);
  const t = parseWoff(readFileSync(file));
  const unitsPerEm = t.get("head").readUInt16BE(18);
  const numberOfHMetrics = t.get("hhea").readUInt16BE(34);
  const hmtx = t.get("hmtx");
  const advance = (gid) => hmtx.readUInt16BE(Math.min(gid, numberOfHMetrics - 1) * 4);
  const cmap = cmapToGlyph(t.get("cmap"));
  const out = {};
  for (const [cp, gid] of [...cmap.entries()].sort((a, b) => a[0] - b[0])) {
    if (cp < 0x20 || cp > 0x2fff) continue;
    out[String.fromCodePoint(cp)] = Math.round((advance(gid) / unitsPerEm) * 1000);
  }
  return out;
}

const table = {};
for (const w of WEIGHTS) table[w] = widthsFor(w);
const body = `// GENERATED by scripts/gen-inter-widths.mjs ${FAMILY} from @fontsource/${FAMILY} ${fontPkg.version} — do not edit.
// Advance widths in 1/1000 em per code point, per weight (latin subset). Kerning is not included;
// the estimator treats this as an upper bound (kerning only tightens).
export const ${CONST}_VERSION = ${JSON.stringify(fontPkg.version)};
export const ${CONST}_WEIGHTS = [${WEIGHTS.join(", ")}] as const;
export type ${CONST[0]}${CONST.slice(1).toLowerCase()}Weight = (typeof ${CONST}_WEIGHTS)[number];
export const ${CONST}_WIDTHS: Record<${CONST[0]}${CONST.slice(1).toLowerCase()}Weight, Readonly<Record<string, number>>> = ${JSON.stringify(table)};
`;
const outFile = path.join(here, "..", "src", "fonts", `${FAMILY}-widths.ts`);
writeFileSync(outFile, body);
console.log(`wrote ${outFile}: ${Object.keys(table[WEIGHTS[0]]).length} code points × ${WEIGHTS.length} weights`);
